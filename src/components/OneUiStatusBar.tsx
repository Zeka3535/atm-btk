/**
 * Статус-бар One UI по SVG опущенной шторки уведомлений:
 * слева часы (white @ 0.8), справа LTE → сигнал → батарея 69.
 */
export function OneUiStatusBar({
  battery = 69,
  signal = 4,
}: {
  battery?: number
  signal?: number
}) {
  const [clock, setClock] = useState(formatClock)

  useEffect(() => {
    const tick = () => setClock(formatClock())
    tick()
    const id = window.setInterval(tick, 15_000)
    return () => window.clearInterval(id)
  }, [])

  return (
    <div className="oneui-statusbar" aria-hidden>
      <span className="oneui-clock">{clock}</span>
      <div className="oneui-sb-right">
        <IconLte />
        <IconSignal level={Math.max(0, Math.min(4, signal))} />
        <IconBattery level={Math.max(0, Math.min(100, Math.round(battery)))} />
      </div>
    </div>
  )
}
